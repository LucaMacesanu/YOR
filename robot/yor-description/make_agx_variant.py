"""Derive yor-full-agx.mjcf / scene-full-agx.mjcf: YOR with the stock AgileX grippers.

yor-full.mjcf carries the custom grippers in BEGIN GRIPPER ... END GRIPPER blocks
(written by output/grippers/attach_to_arm.py). This swaps each block for the AgileX
parallel-jaw gripper, so the two models differ only there. Re-run after yor-full.mjcf
is regenerated:

    python robot/yor-description/make_agx_variant.py

The gripper is the one on the Piper (robot/arm/mujoco/piper_right.xml): gripper_base.stl
plus two sliding fingers (gripper_link7.stl = Piper's link7.stl, link8.stl), 0..35 mm
each (70 mm stroke), 0 = closed. It is seated on the stand_v2 face like the custom
gripper and approaches along link7 +y; the jaws close along link7 z, the plane the
custom fingers close in. Placeholder: the real mount offset and jaw orientation on the
Nero flange are not measured.
"""

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "yor-full.mjcf"
OUT = HERE / "yor-full-agx.mjcf"
SCENE_SRC = HERE / "scene-full.mjcf"
SCENE_OUT = HERE / "scene-full-agx.mjcf"

FINGER_TRAVEL = 0.035  # m per finger
# gripper_base origin in the end-effector body frame: on the stand_v2 face (link7 y = 0.045)
MOUNT_POS = "0 0.012 0"
MOUNT_QUAT = "0.707107 -0.707107 0 0"  # base +z (approach) -> link7 +y, base y (jaws) -> link7 -z

TAG = "<!-- {} AGX GRIPPER ({}): generated by robot/yor-description/make_agx_variant.py - do not hand-edit. -->"

DEFAULTS = f"""
    <default class="agx_gripper">
      <joint type="slide" axis="0 0 1" range="0 {FINGER_TRAVEL}" damping="2" armature="0.001" frictionloss="0.01"/>
      <position kp="400" dampratio="1" forcerange="-20 20" inheritrange="1"/>
      <default class="agx_gripper_visual">
        <geom type="mesh" contype="0" conaffinity="0" group="2" density="0" material="gray_mat"/>
      </default>
      <default class="agx_gripper_collision">
        <geom group="3" friction="2 0.005 0.0001" condim="4" density="0"/>
      </default>
    </default>"""

MESHES = """
    <mesh name="agx_gripper_base" file="gripper_base.stl"/>
    <mesh name="agx_finger_a" file="gripper_link7.stl"/>
    <mesh name="agx_finger_b" file="link8.stl"/>"""


def finger(side, letter, quat):
    # Piper's finger pads as collision boxes; the mesh inner face is local z = 0
    return f"""
                                    <body name="{side}_gripper_finger_{letter}" pos="0 0 0.1358" quat="{quat}">
                                      <inertial pos="0.000651232 -0.049193 0.00972259" quat="0.477798 0.572974 -0.518028 0.418398" mass="0.025" diaginertia="7.74531e-05 7.36783e-05 5.0886e-06"/>
                                      <joint name="{side}_gripper_finger_{letter}"/>
                                      <geom class="agx_gripper_visual" mesh="agx_finger_{letter}"/>
                                      <geom class="agx_gripper_collision" type="box" size="0.012 0.015 0.0025" pos="0 -0.015 0.0025"/>
                                      <geom class="agx_gripper_collision" type="box" size="0.015 0.015 0.0025" pos="0 -0.045 0.0025"/>
                                    </body>"""


def body(side):
    return f"""
                                  <body name="{side}_gripper_base" childclass="agx_gripper" pos="{MOUNT_POS}" quat="{MOUNT_QUAT}">
                                    <inertial pos="-0.000183807 8.05033e-05 0.0321437" quat="0.999976 9.08444e-05 0.00689649 0.000788512" mass="0.45" diaginertia="0.000929442 0.000714469 0.000394318"/>
                                    <geom class="agx_gripper_visual" mesh="agx_gripper_base"/>
                                    <geom class="agx_gripper_collision" type="mesh" mesh="agx_gripper_base"/>
                                    <site name="{side}_gripper_center" pos="0 0 0.12"/>""" + \
        finger(side, "a", "0.707105 0.707108 0 0") + \
        finger(side, "b", "-2.59734e-06 -2.59735e-06 -0.707108 -0.707105") + """
                                  </body>"""


ACTUATORS = "".join(
    f'\n    <position name="{s}_gripper_finger_{f}_pos" joint="{s}_gripper_finger_{f}" class="agx_gripper"/>'
    for s in ("left", "right") for f in ("a", "b"))

CONTACTS = "".join(
    f'\n    <exclude body1="{s}_gripper_base" body2="{s}_gripper_finger_{f}"/>' for s in ("left", "right") for f in ("a", "b")
) + "".join(
    f'\n    <exclude body1="{s}_arm_end_effector" body2="{s}_gripper_base"/>'
    f'\n    <exclude body1="{s}_arm_link7" body2="{s}_gripper_base"/>' for s in ("left", "right"))

REPLACEMENTS = {
    "defaults": DEFAULTS,
    "meshes": MESHES,
    "left gripper": body("left"),
    "right gripper": body("right"),
    "actuators": ACTUATORS,
    "contacts": CONTACTS,
}

BLOCK = re.compile(r"(?P<indent>[ \t]*)<!-- BEGIN GRIPPER \((?P<label>[^)]+)\).*?<!-- END GRIPPER -->", re.S)


def main():
    text = SRC.read_text(encoding="utf-8")
    seen = set()

    def swap(m):
        label, indent = m["label"], m["indent"]
        seen.add(label)
        return f"{indent}{TAG.format('BEGIN', label)}{REPLACEMENTS[label]}\n{indent}<!-- END AGX GRIPPER -->"

    text = BLOCK.sub(swap, text)
    missing = set(REPLACEMENTS) - seen
    if missing:
        raise SystemExit(f"{SRC.name}: no BEGIN GRIPPER block for {sorted(missing)}")

    text = text.replace('<mujoco model="yor-full">', '<mujoco model="yor-full-agx">', 1)
    text = text.replace(
        "<!-- YOR, full robot:",
        "<!-- GENERATED from yor-full.mjcf by make_agx_variant.py (stock AgileX grippers); edit that file.\n"
        "       YOR, full robot:", 1)
    text = text.replace("then left_gripper joint1-2, right_gripper joint1-2,",
                        "then left_gripper finger_a/b, right_gripper finger_a/b,")
    # the keyframe's gripper qpos/ctrl slots line up (2 joints and 2 actuators per arm);
    # 0 is closed for these fingers, which the sim opens on its first tick
    OUT.write_text(text, encoding="utf-8")

    scene = SCENE_SRC.read_text(encoding="utf-8")
    scene = scene.replace('model="scene-full"', 'model="scene-full-agx"').replace('file="yor-full.mjcf"', 'file="yor-full-agx.mjcf"')
    SCENE_OUT.write_text(scene, encoding="utf-8")
    print(f"wrote {OUT.name}, {SCENE_OUT.name}")


if __name__ == "__main__":
    main()
